drop table if exists conversation_entry;

create table conversation_entry (
    id integer generated by default as identity not null,
    version integer not null,
    content varchar(1000) not null,
    participant_name varchar(100) not null,
    participant_lap_time_at_posting interval,
    parent_entry_id integer,
    challenge_id integer not null,
    created_at timestamp not null,
    modified_at timestamp,

    primary key (id),

    constraint FK_conversation_entry_challenge
        foreign key (challenge_id) references challenge
);

-- supports loading a challenge's conversation in its configured chronological order
create index idx_conversation_entry_challenge_created_id
    on conversation_entry (challenge_id, created_at, id);

-- supports finding replies when a parent entry is deleted
create index idx_conversation_entry_parent_entry_id
    on conversation_entry (parent_entry_id);

